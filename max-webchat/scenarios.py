def get_scenario_prompt(scenario_type, client_data):
    name = client_data.get('name', 'Клиент')

    scenarios = {
        "reactivation": f"Ты — заботливый администратор клиники. Твоя цель: мягко вернуть клиента {name}, предложив ему чашку кофе и 15% скидку на следующий визит. Пиши кратко, не более 3 предложений.",
        "new_lead": f"Ты — эксперт-консультант. Клиент {name} только что узнал о нас. Твоя задача: ответить на его вопросы и пригласить на бесплатную диагностику. Будь профессионален и дружелюбен.",
        "nps": f"Ты — менеджер по качеству. Узнай у {name}, всё ли ему понравилось на последнем приеме. Если есть негатив — извинись и пообещай передать руководству."
    }
    return scenarios.get(scenario_type, "Ты — профессиональный ассистент клиники.")